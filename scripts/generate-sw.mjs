import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
async function files(dir){const list=[];for(const f of await readdir(dir,{withFileTypes:true})){if(f.isDirectory())list.push(...(await files(`${dir}/${f.name}`)));else if(f.name!=='sw.js')list.push(`${dir}/${f.name}`);}return list;}
const paths=(await files('dist')).sort();
const hash=createHash('sha256');for(const p of paths)hash.update(await readFile(p));
const version=hash.digest('hex').slice(0,16);
await writeFile('dist/sw.js',`// Generated by scripts/generate-sw.mjs; never cache remote sites.
const PREFIX='bookmark-hub:'+self.registration.scope+':';
const CACHE=PREFIX+'${version}';
const ASSETS=${JSON.stringify(paths.map(p=>'./'+p.slice(5)))};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS))));
// Wait for old tabs to close: do not replace a running app mid-edit.
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const key of await caches.keys())if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);await self.clients.claim();})()));
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET'||url.origin!==self.location.origin||!url.href.startsWith(self.registration.scope))return;
 event.respondWith((async()=>{
  const cache=await caches.open(CACHE);
  if(event.request.mode==='navigate')return (await cache.match('./index.html',{ignoreVary:true}))||fetch(event.request);
  return (await cache.match(event.request,{ignoreVary:true}))||fetch(event.request);
 })());
});
`);
console.log(`Service Worker generated: ${paths.length} local files, version ${version}`);

